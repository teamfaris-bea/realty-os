// Generates packages/db/src/schema.ts (the Kysely `DB` interface) from information_schema.
//
// schema.ts is a checked-in, hand-reviewable file. It is produced by this generator from a database
// with every migration applied, and test/schema_drift.test.ts regenerates it from a fresh per-test
// database and requires byte equality, so the interfaces can never drift from the migrations
// (BUILD_PLAN module 7 "Kysely interfaces match information_schema").
//
//   pnpm --filter @realty/db gen-schema          # rewrites src/schema.ts from a fresh test database
//
// Type mapping (pg driver as configured by createDatabase(): int8/numeric stay strings, `date` stays
// a 'YYYY-MM-DD' string, timestamptz is a Date):
//   uuid/text/citext/inet/tsvector/time/date → string     int2/int4 → number     int8/numeric → string
//   timestamptz → Timestamp (Date, insert Date | ISO string)  bool → boolean   bytea → Buffer
//   jsonb → Json (selected as a value; inserted as a JSON string, see `json()`)   text[] → string[]
// Columns with a default (or GENERATED BY DEFAULT AS IDENTITY) are `Generated<T>`; GENERATED ALWAYS
// columns (stored generated tsvectors, `jobs.id`, `audit_log.seq`) are `GeneratedAlways<T>`.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import pg from 'pg';

export interface ColumnInfo {
  table_name: string;
  table_type: string;
  column_name: string;
  data_type: string;
  udt_name: string;
  is_nullable: string;
  column_default: string | null;
  is_generated: string;
  is_identity: string;
  identity_generation: string | null;
}

export const COLUMNS_SQL = `
  SELECT c.table_name::text, t.table_type::text, c.column_name::text, c.data_type::text, c.udt_name::text,
         c.is_nullable::text, c.column_default::text, c.is_generated::text, c.is_identity::text,
         c.identity_generation::text
    FROM information_schema.columns c
    JOIN information_schema.tables t ON t.table_schema = c.table_schema AND t.table_name = c.table_name
   WHERE c.table_schema = 'public'
   ORDER BY c.table_name, c.ordinal_position`;

const BASE_TYPES: Record<string, string> = {
  uuid: 'string',
  text: 'string',
  varchar: 'string',
  citext: 'string',
  inet: 'string',
  tsvector: 'string',
  time: 'string',
  date: 'string',
  int2: 'number',
  int4: 'number',
  int8: 'Int8',
  numeric: 'Numeric',
  bool: 'boolean',
  bytea: 'Buffer',
  jsonb: 'Json',
  json: 'Json',
  timestamptz: 'Timestamp',
  _text: 'string[]',
  _uuid: 'string[]',
};

export function pascal(name: string): string {
  return name
    .split('_')
    .filter(Boolean)
    .map((p) => p[0]!.toUpperCase() + p.slice(1))
    .join('');
}

function tsType(c: ColumnInfo): string {
  const base = BASE_TYPES[c.udt_name];
  if (!base) throw new Error(`schemaGen: no TypeScript mapping for ${c.table_name}.${c.column_name} (${c.udt_name})`);
  const isView = c.table_type === 'VIEW';
  // views report every column as nullable; base tables use the real NOT NULL flag
  const nullable = isView || c.is_nullable === 'YES' ? `${base} | null` : base;
  if (isView) return nullable;
  if (c.is_generated === 'ALWAYS' || (c.is_identity === 'YES' && c.identity_generation === 'ALWAYS')) {
    return `GeneratedAlways<${nullable}>`;
  }
  if (c.column_default !== null || c.is_identity === 'YES') return `Generated<${nullable}>`;
  return nullable;
}

export function renderSchema(columns: readonly ColumnInfo[]): string {
  const byTable = new Map<string, ColumnInfo[]>();
  for (const c of columns) {
    const list = byTable.get(c.table_name);
    if (list) list.push(c);
    else byTable.set(c.table_name, [c]);
  }
  const names = [...byTable.keys()].sort();
  const out: string[] = [];
  out.push('// GENERATED by packages/db/src/schemaGen.ts from information_schema (every migration applied).');
  out.push('// Do not edit by hand: run `pnpm --filter @realty/db gen-schema`. test/schema_drift.test.ts fails');
  out.push('// when this file differs from what the migrations produce (BUILD_PLAN module 7).');
  out.push("import type { ColumnType, Generated, GeneratedAlways } from 'kysely';");
  out.push('');
  out.push('/** timestamptz: selected as a Date; inserted/updated as a Date or an ISO-8601 string with offset. */');
  out.push('export type Timestamp = ColumnType<Date, Date | string, Date | string>;');
  out.push('/** int8: the pg driver returns a decimal string (no precision loss); write a number, bigint or string. */');
  out.push('export type Int8 = ColumnType<string, string | number | bigint, string | number | bigint>;');
  out.push('/** numeric: returned as a decimal string. */');
  out.push('export type Numeric = ColumnType<string, string | number, string | number>;');
  out.push('export type JsonPrimitive = string | number | boolean | null;');
  out.push('export type JsonValue = JsonPrimitive | JsonValue[] | { [k: string]: JsonValue };');
  out.push('/** jsonb: selected as a parsed value; written as a JSON string (use `json(value)` from @realty/db). */');
  out.push('export type Json = ColumnType<JsonValue, string, string>;');
  out.push('');
  for (const t of names) {
    const cols = byTable.get(t)!;
    const kind = cols[0]!.table_type === 'VIEW' ? 'view' : 'table';
    out.push(`/** public.${t} (${kind}) */`);
    out.push(`export interface ${pascal(t)}Table {`);
    for (const c of cols) out.push(`  ${c.column_name}: ${tsType(c)};`);
    out.push('}');
    out.push('');
  }
  out.push('/** Every table and view in schema public. */');
  out.push('export interface DB {');
  for (const t of names) out.push(`  ${t}: ${pascal(t)}Table;`);
  out.push('}');
  out.push('');
  out.push(`/** Table names (base tables only), in alphabetical order. */`);
  out.push('export const TABLE_NAMES = [');
  for (const t of names.filter((n) => byTable.get(n)![0]!.table_type !== 'VIEW')) out.push(`  '${t}',`);
  out.push('] as const;');
  out.push('');
  out.push(`/** View names, in alphabetical order. */`);
  out.push('export const VIEW_NAMES = [');
  for (const t of names.filter((n) => byTable.get(n)![0]!.table_type === 'VIEW')) out.push(`  '${t}',`);
  out.push('] as const;');
  out.push('');
  return out.join('\n');
}

export async function generateSchema(ownerUrl: string): Promise<string> {
  const c = new pg.Client({ connectionString: ownerUrl, application_name: 'realty-schema-gen' });
  await c.connect();
  try {
    const { rows } = await c.query<ColumnInfo>(COLUMNS_SQL);
    return renderSchema(rows);
  } finally {
    await c.end();
  }
}

export const SCHEMA_FILE = fileURLToPath(new URL('./schema.ts', import.meta.url));

// CLI: tsx src/schemaGen.ts
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { createTestDb } = await import('./testing/index.js');
  const db = await createTestDb();
  try {
    const text = await generateSchema(db.ownerUrl);
    writeFileSync(SCHEMA_FILE, text);
    console.log(`wrote ${SCHEMA_FILE}`);
  } finally {
    await db.drop();
  }
}
