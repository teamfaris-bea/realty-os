// The consent ledger fold and its write-side rules (R-CONSENT-1…4, R-CONSENT-8, R-CONSENT-10).
//
// `consent_events` is append-only; `consent_state` is ALWAYS `projectConsent(events)` for the key,
// written in the same transaction (R-CONSENT-6, db/client `recordConsentEvent`). The fold:
//
// - Keys are (channel, purpose, address HMAC), never a contact (R-CONSENT-1). An event with
//   purpose `all` belongs to both purpose keys.
// - Events are ordered by (occurred_at, id), the order of `consent_events_key_idx`.
// - A revoke beats every earlier grant. After a revoke, only the person's own action reinstates
//   (R-CONSENT-10, ARCHITECTURE C11):
//     * START/UNSTOP (`resubscribe`, SMS keyword) undoes keyword revokes only, restoring exactly the
//       state before the STOP; grants recorded while opted out stay ignored;
//     * a new form submission with a disclosure (`web_form` / `lead_provider` + disclosure);
//     * a signed document recorded with evidence (`signed_document` + evidence object).
//   No staff entry, verbal note, first text or import ever reinstates an opt-out.
// - `expire` ends every earlier grant (status `none`, not an opt-out).
// - An `inquiry` basis past `expires_at` projects to `none` at evaluation time (R-CONSENT-2); one
//   without `expires_at` is never valid. Future-dated grants do not count yet.
// - Imported grants count at most at `imported_unverified` (R-CONSENT-3). `import_revert` voids the
//   imported grant it cites and never a revocation.
// - "Not an opt-out" (R-CONSENT-8): an agent's review of an opt-out-LANGUAGE revoke is recorded as a
//   void marker (see `planNotAnOptOut`). The fold drops that revoke and recomputes, so the prior
//   level comes back only if its basis still exists. A marker that cites anything other than an
//   `inbound_language` revoke is ignored, and a marker is never itself a grant.
//
// Level of a granted key = the strongest valid grant since the last reset; its basis is the latest
// event at that level, and `expires_at` is that basis's.
import type { IdGenerator, Instant } from '../foundation/index.js';
import { DAY_MS, instant } from '../foundation/index.js';
import { containsName } from './content.js';
import {
  type AddressKind,
  type Channel,
  type ConsentEventType,
  type ConsentKey,
  type ConsentLevel,
  type ConsentSource,
  type ConsentStateRow,
  type EventPurpose,
  PURPOSES,
  type Purpose,
  consentKey,
  levelRank,
} from './types.js';

/** The `consent_events.evidence` key that marks an R-CONSENT-8 "not an opt-out" review. */
export const VOIDS_REVOKE_EVIDENCE_KEY = 'voids_revoke_event_id';

/** Insert shape of one `consent_events` row (ids are generated by core). */
export interface ConsentEventSpec {
  id: string;
  addressKind: AddressKind;
  addressHmac: string;
  addressHint: string;
  channel: Channel;
  purpose: EventPurpose;
  eventType: ConsentEventType;
  level: ConsentLevel;
  source: ConsentSource;
  occurredAt: Instant;
  contactId: string | null;
  actor: { kind: 'user'; userId: string } | { kind: 'system' };
  disclosureId: string | null;
  evidenceObjectId: string | null;
  evidenceMessageId: string | null;
  evidenceCallId: string | null;
  evidenceCallOffsetMs: number | null;
  evidence: Record<string, unknown>;
  imported: boolean;
  importRecordId: string | null;
  originalProvenance: Record<string, unknown> | null;
  revertsEventId: string | null;
  expiresAt: Instant | null;
  needsReview: boolean;
}

/** What the fold needs from a stored event (map a DB row or a spec with `toConsentEvent`). */
export interface ConsentEvent {
  id: string;
  channel: Channel;
  purpose: EventPurpose;
  addressHmac: string;
  eventType: ConsentEventType;
  level: ConsentLevel;
  source: ConsentSource;
  occurredAt: Instant;
  imported: boolean;
  actorKind: 'user' | 'system';
  disclosureId: string | null;
  evidenceObjectId: string | null;
  revertsEventId: string | null;
  expiresAt: Instant | null;
  evidence?: Record<string, unknown>;
}

export function toConsentEvent(s: ConsentEventSpec): ConsentEvent {
  return {
    id: s.id,
    channel: s.channel,
    purpose: s.purpose,
    addressHmac: s.addressHmac,
    eventType: s.eventType,
    level: s.level,
    source: s.source,
    occurredAt: s.occurredAt,
    imported: s.imported,
    actorKind: s.actor.kind,
    disclosureId: s.disclosureId,
    evidenceObjectId: s.evidenceObjectId,
    revertsEventId: s.revertsEventId,
    expiresAt: s.expiresAt,
    evidence: s.evidence,
  };
}

// ---- fold ---------------------------------------------------------------------------------------

function voidsTarget(e: ConsentEvent): string | null {
  const v = e.evidence?.[VOIDS_REVOKE_EVIDENCE_KEY];
  return typeof v === 'string' ? v : null;
}

/**
 * Markers are never counted as consent. Only a GRANT can be a "not an opt-out" marker: a revoke (or
 * resubscribe/expire) that happens to carry the evidence key is still applied as what it is, so an
 * evidence field can never hide an opt-out.
 */
function isMarker(e: ConsentEvent): boolean {
  return e.eventType === 'import_revert' || (e.eventType === 'grant' && voidsTarget(e) !== null);
}

/** The exact shape `planNotAnOptOut` writes: an agent_entry grant by a user, not imported. */
function isNotAnOptOutMarker(e: ConsentEvent): boolean {
  return e.eventType === 'grant' && e.source === 'agent_entry' && e.actorKind === 'user' && !e.imported && voidsTarget(e) !== null;
}

/**
 * Whether a grant reinstates after an opt-out (R-CONSENT-10: only the person's own action). A form
 * or lead-provider submission is the person's action only when the intake pipeline (a system
 * actor) wrote it: the consent_events INSERT policy lets any member write any source as
 * themselves, so a staff-written "web_form" grant must not be able to override an opt-out.
 */
function reinstates(e: ConsentEvent): boolean {
  if (e.imported) return false;
  if ((e.source === 'web_form' || e.source === 'lead_provider') && e.disclosureId !== null) return e.actorKind === 'system';
  return e.source === 'signed_document' && e.evidenceObjectId !== null;
}

/** START/UNSTOP is the person's own keyword, ingested by the system (never staff, never imported). */
function isPersonsResubscribe(e: ConsentEvent): boolean {
  return e.actorKind === 'system' && !e.imported && e.channel === 'sms' && e.source === 'inbound_keyword';
}

function cappedLevel(e: ConsentEvent): ConsentLevel {
  return e.imported && levelRank(e.level) > levelRank('imported_unverified') ? 'imported_unverified' : e.level;
}

function compareEvents(a: ConsentEvent, b: ConsentEvent): number {
  if (a.occurredAt !== b.occurredAt) return a.occurredAt - b.occurredAt;
  return a.id < b.id ? -1 : 1; // ids are unique
}

/** Ids voided by valid `import_revert` events and valid "not an opt-out" markers. */
function voidedIds(events: readonly ConsentEvent[]): Set<string> {
  const byId = new Map(events.map((e) => [e.id, e]));
  const voided = new Set<string>();
  for (const e of events) {
    if (e.eventType === 'import_revert' && e.revertsEventId !== null) {
      const t = byId.get(e.revertsEventId);
      if (t && t.eventType === 'grant' && t.imported) voided.add(t.id);
    }
    const target = isNotAnOptOutMarker(e) ? voidsTarget(e) : null;
    if (target !== null) {
      const t = byId.get(target);
      if (t && t.eventType === 'revoke' && t.source === 'inbound_language' && t.occurredAt <= e.occurredAt) voided.add(t.id);
    }
  }
  return voided;
}

interface Frame {
  grants: ConsentEvent[];
  revoke: ConsentEvent | null;
  keyword: boolean;
  below: Frame | null;
}

function foldKey(events: readonly ConsentEvent[], voided: ReadonlySet<string>, now: Instant): Omit<ConsentStateRow, 'channel' | 'purpose' | 'addressHmac' | 'ledgerEventCount'> {
  let f: Frame = { grants: [], revoke: null, keyword: false, below: null };
  for (const e of events) {
    if (voided.has(e.id) || isMarker(e)) continue;
    switch (e.eventType) {
      case 'grant':
        if (f.revoke === null) f.grants.push(e);
        else if (reinstates(e)) f = { grants: [e], revoke: null, keyword: false, below: null };
        break;
      case 'revoke':
        f = { grants: [], revoke: e, keyword: e.source === 'inbound_keyword', below: f };
        break;
      case 'resubscribe':
        if (!isPersonsResubscribe(e)) break;
        while (f.revoke !== null && f.keyword && f.below !== null) f = f.below;
        break;
      case 'expire':
        for (let x: Frame | null = f; x !== null; x = x.below) x.grants = [];
        break;
      // import_revert never gets here: it is a marker (skipped above).
    }
  }
  if (f.revoke !== null) return { status: 'revoked', level: 'none', basisEventId: f.revoke.id, expiresAt: null };
  let best: ConsentEvent | null = null;
  for (const g of f.grants) {
    if (g.occurredAt > now) continue;
    if (g.expiresAt !== null && g.expiresAt <= now) continue;
    if (g.level === 'inquiry' && g.expiresAt === null) continue;
    if (best === null || levelRank(cappedLevel(g)) >= levelRank(cappedLevel(best))) best = g;
  }
  if (best === null) return { status: 'none', level: 'none', basisEventId: null, expiresAt: null };
  return { status: 'granted', level: cappedLevel(best), basisEventId: best.id, expiresAt: best.expiresAt };
}

/**
 * Projects the ledger into `consent_state` rows, one per (channel, purpose, address) that has at
 * least one event. Pure and order-independent: the input order does not matter.
 */
export function projectConsent(events: readonly ConsentEvent[], now: Instant): Map<ConsentKey, ConsentStateRow> {
  const byAddress = new Map<string, ConsentEvent[]>();
  for (const e of events) {
    const k = `${e.channel}:${e.addressHmac}`;
    const list = byAddress.get(k);
    if (list) list.push(e);
    else byAddress.set(k, [e]);
  }
  const out = new Map<ConsentKey, ConsentStateRow>();
  for (const list of [...byAddress.values()]) {
    const sorted = [...list].sort(compareEvents);
    const voided = voidedIds(sorted);
    const first = sorted[0] as ConsentEvent;
    for (const purpose of PURPOSES) {
      const relevant = sorted.filter((e) => e.purpose === purpose || e.purpose === 'all');
      if (relevant.length === 0) continue;
      out.set(consentKey(first.channel, purpose, first.addressHmac), {
        channel: first.channel,
        purpose,
        addressHmac: first.addressHmac,
        ...foldKey(relevant, voided, now),
        ledgerEventCount: relevant.length,
      });
    }
  }
  return out;
}

/**
 * The level a stored `consent_state` row grants at `now` (R-CONSENT-2: an expired basis is
 * `none` at evaluation time). Missing, revoked and `none` rows grant nothing.
 */
export function effectiveLevel(row: ConsentStateRow | undefined, now: Instant): ConsentLevel {
  if (!row || row.status !== 'granted') return 'none';
  if (row.expiresAt !== null && row.expiresAt <= now) return 'none';
  if (row.level === 'inquiry' && row.expiresAt === null) return 'none';
  return row.level;
}

// ---- write-side checks (mirror the consent_events CHECKs so the API can reject early) ----------

export type ConsentSpecIssue =
  | 'CHANNEL_KIND_MISMATCH'
  | 'IMPORTED_SOURCE_MISMATCH'
  | 'IMPORTED_PROVENANCE_MISSING'
  | 'IMPORTED_GRANT_ABOVE_CAP'
  | 'UNVERIFIED_LEVEL_NOT_IMPORTED'
  | 'EXPRESS_WRITTEN_WITHOUT_EVIDENCE'
  | 'VERBAL_WITHOUT_CALL'
  | 'AGENT_ENTRY_ABOVE_EXPRESS'
  | 'INBOUND_FIRST_CONTACT_SHAPE'
  | 'SIGNED_DOCUMENT_WITHOUT_EVIDENCE'
  | 'NON_GRANT_WITH_LEVEL'
  | 'GRANT_WITHOUT_LEVEL'
  | 'RESUBSCRIBE_SHAPE'
  | 'REVERT_REFERENCE'
  | 'INQUIRY_WITHOUT_EXPIRY'
  | 'HINT_TOO_LONG'
  | 'NEGATIVE_CALL_OFFSET';

/** Every DB CHECK on consent_events (R-CONSENT-3, R-CONSENT-4) as a list of violated issues. */
export function validateConsentEventSpec(s: ConsentEventSpec): ConsentSpecIssue[] {
  const issues: ConsentSpecIssue[] = [];
  const isImportSource = s.source === 'import_fub' || s.source === 'import_csv';
  if ((s.addressKind === 'phone') !== (s.channel !== 'email')) issues.push('CHANNEL_KIND_MISMATCH');
  if (s.imported !== isImportSource) issues.push('IMPORTED_SOURCE_MISMATCH');
  if (s.imported && (s.importRecordId === null || s.originalProvenance === null)) issues.push('IMPORTED_PROVENANCE_MISSING');
  if (s.imported && s.eventType === 'grant' && s.level !== 'imported_unverified') issues.push('IMPORTED_GRANT_ABOVE_CAP');
  if (!s.imported && s.level === 'imported_unverified') issues.push('UNVERIFIED_LEVEL_NOT_IMPORTED');
  if (s.level === 'express_written' && s.disclosureId === null && s.evidenceObjectId === null) issues.push('EXPRESS_WRITTEN_WITHOUT_EVIDENCE');
  if (s.source === 'verbal_on_call' && s.evidenceCallId === null) issues.push('VERBAL_WITHOUT_CALL');
  if (s.source === 'agent_entry' && s.level !== 'none' && s.level !== 'express') issues.push('AGENT_ENTRY_ABOVE_EXPRESS');
  if (s.source === 'inbound_first_contact' && !(s.level === 'express' && s.purpose === 'informational')) issues.push('INBOUND_FIRST_CONTACT_SHAPE');
  if (s.source === 'signed_document' && s.evidenceObjectId === null) issues.push('SIGNED_DOCUMENT_WITHOUT_EVIDENCE');
  if ((s.eventType === 'revoke' || s.eventType === 'expire' || s.eventType === 'import_revert') && s.level !== 'none') issues.push('NON_GRANT_WITH_LEVEL');
  if (s.eventType === 'grant' && s.level === 'none') issues.push('GRANT_WITHOUT_LEVEL');
  if (s.eventType === 'resubscribe' && !(s.channel === 'sms' && s.source === 'inbound_keyword')) issues.push('RESUBSCRIBE_SHAPE');
  if ((s.eventType === 'import_revert') !== (s.revertsEventId !== null)) issues.push('REVERT_REFERENCE');
  if (s.level === 'inquiry' && s.expiresAt === null) issues.push('INQUIRY_WITHOUT_EXPIRY');
  if (s.addressHint.length > 40) issues.push('HINT_TOO_LONG');
  if (s.evidenceCallOffsetMs !== null && s.evidenceCallOffsetMs < 0) issues.push('NEGATIVE_CALL_OFFSET');
  return issues;
}

// ---- disclosures (R-CONSENT-4) ------------------------------------------------------------------

/** Whether a disclosure's `names_seller` names this tenant (brokerage legal name or team name). */
export function disclosureNamesTenant(namesSeller: string, tenantNames: readonly (string | null | undefined)[]): boolean {
  return tenantNames.some((n) => typeof n === 'string' && containsName(namesSeller, n));
}

/**
 * The level a written disclosure supports (R-CONSENT-4, E38): `express_written` only when the text
 * names this tenant/brokerage; otherwise (e.g. a lead provider's text naming another company)
 * `inquiry`, expiring after the pack's inquiry window. VERIFY WITH COUNSEL.
 */
export function levelForDisclosure(i: {
  namesSeller: string;
  tenantNames: readonly (string | null | undefined)[];
  occurredAt: Instant;
  inquiryBasisDays: number;
}): { level: 'express_written' | 'inquiry'; expiresAt: Instant | null } {
  if (disclosureNamesTenant(i.namesSeller, i.tenantNames)) return { level: 'express_written', expiresAt: null };
  return { level: 'inquiry', expiresAt: instant(i.occurredAt + i.inquiryBasisDays * DAY_MS) };
}

// ---- "not an opt-out" (R-CONSENT-8) -------------------------------------------------------------

export type NotAnOptOutResult =
  | {
      ok: true;
      /** The marker for the reviewed revoke (also `events[0]`). */
      event: ConsentEventSpec;
      /**
       * One marker per opt-out-language revoke the same inbound message wrote (the sender's phone,
       * the contact's other phones, a named channel): the message was not an opt-out, so none of its
       * revokes stand. Append all of them in one transaction.
       */
      events: ConsentEventSpec[];
      restored: ConsentStateRow[];
    }
  | { ok: false; code: 'CONSENT_EVENT_NOT_FOUND' | 'NOT_AN_OPT_OUT_LANGUAGE_REVOKE' | 'ALREADY_REVIEWED' };

/**
 * An agent marks an opt-out-language revoke as "not an opt-out". The review covers the inbound
 * message, so every opt-out-language revoke that message wrote gets a marker (`events`); otherwise a
 * revoke left on the contact's other phone would keep blocking SMS. Returns the void markers to append
 * (a `grant` from `agent_entry` at `express`, which satisfies every consent_events CHECK, carrying
 * `evidence.voids_revoke_event_id`; the fold never treats it as a grant) and the rows it restores.
 * The prior level comes back only if its basis still exists (e.g. an expired inquiry stays `none`).
 * Keyword STOPs, provider reports and wrong-number revokes can never be reviewed away. The caller
 * audits it with the agent's reason (R-CONSENT-8).
 */
export function planNotAnOptOut(i: {
  events: readonly ConsentEventSpec[];
  revokeEventId: string;
  userId: string;
  now: Instant;
  ids: IdGenerator;
}): NotAnOptOutResult {
  const target = i.events.find((e) => e.id === i.revokeEventId);
  if (!target) return { ok: false, code: 'CONSENT_EVENT_NOT_FOUND' };
  if (target.eventType !== 'revoke' || target.source !== 'inbound_language') return { ok: false, code: 'NOT_AN_OPT_OUT_LANGUAGE_REVOKE' };
  const reviewed = (t: ConsentEventSpec): boolean => i.events.some((e) => e.evidence[VOIDS_REVOKE_EVIDENCE_KEY] === t.id && e.actor.kind === 'user');
  if (reviewed(target)) return { ok: false, code: 'ALREADY_REVIEWED' };
  // The sibling revokes written by the same inbound message (same evidence message, same instant).
  const siblings =
    target.evidenceMessageId === null
      ? []
      : i.events.filter(
          (e) =>
            e.id !== target.id &&
            e.eventType === 'revoke' &&
            e.source === 'inbound_language' &&
            e.evidenceMessageId === target.evidenceMessageId &&
            e.occurredAt === target.occurredAt &&
            !reviewed(e),
        );
  const marker = (t: ConsentEventSpec): ConsentEventSpec => ({
    id: i.ids.next<'ConsentEventId'>(),
    addressKind: t.addressKind,
    addressHmac: t.addressHmac,
    addressHint: t.addressHint,
    channel: t.channel,
    purpose: t.purpose,
    eventType: 'grant',
    level: 'express',
    source: 'agent_entry',
    occurredAt: i.now,
    contactId: t.contactId,
    actor: { kind: 'user', userId: i.userId },
    disclosureId: null,
    evidenceObjectId: null,
    evidenceMessageId: null,
    evidenceCallId: null,
    evidenceCallOffsetMs: null,
    evidence: { [VOIDS_REVOKE_EVIDENCE_KEY]: t.id },
    imported: false,
    importRecordId: null,
    originalProvenance: null,
    revertsEventId: null,
    expiresAt: null,
    needsReview: false,
  });
  const targets = [target, ...siblings];
  const events = targets.map(marker);
  const rows = projectConsent([...i.events, ...events].map(toConsentEvent), i.now);
  const restored: ConsentStateRow[] = [];
  for (const t of targets) {
    const purposes: readonly Purpose[] = t.purpose === 'all' ? PURPOSES : [t.purpose];
    for (const p of purposes) restored.push(rows.get(consentKey(t.channel, p, t.addressHmac)) as ConsentStateRow);
  }
  return { ok: true, event: events[0] as ConsentEventSpec, events, restored };
}
